def md_escape(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render_module_md(module: str, eps: list[dict]) -> str:
    lines = [
        f"# `{module}`",
        "",
        f"Source: `{eps[0]['file']}` · {len(eps)} endpoint(s)",
        "",
        EXTENSION_BANNER if EXTENSION else GENERATED_BANNER,
        "",
    ]
    for ep in eps:
        verbs = "/".join(ep["methods"])
        lines += [f"## `{ep['name']}`", ""]
        lines += [f"`{verbs} /api/method/{ep['dotted']}`", ""]
        lines += [f"**Auth (derived from code):** {auth_display(ep)}", ""]
        if ep["doc"]["summary"]:
            lines += [ep["doc"]["summary"], ""]
        if ep["doc"]["description"]:
            lines += [ep["doc"]["description"], ""]
        if ep["params"]:
            lines += [
                "| arg | type | required | default | description |",
                "|---|---|---|---|---|",
            ]
            for p in ep["params"]:
                schema = p["schema"]
                typ = schema.get("type", "")
                if isinstance(typ, list):
                    typ = " \\| ".join(typ)
                if not typ:
                    typ = schema.get("description", "").strip("()")
                lines.append(
                    "| `{}` | {} | {} | {} | {} |".format(
                        p["name"],
                        typ or "—",
                        "yes" if p["required"] else "no",
                        f"`{p['default']}`" if p["default"] else "—",
                        md_escape(p["desc"] or ""),
                    )
                )
            lines.append("")
        for section in ("Payload", "Returns", "Raises", "Permissions", "Notes"):
            content = section_text(ep, section)
            if content:
                lines += [f"**{section}:** {content}", ""]
        example = "\n".join(ep["doc"]["sections"].get("Example", []))
        if example.strip():
            lines += ["```", example.strip("\n"), "```", ""]
        lines += [f"<sub>`{ep['file']}:{ep['line']}`</sub>", ""]
    return "\n".join(lines).rstrip() + "\n"


def render_index_md(endpoints: list[dict], doctypes: list[dict]) -> str:
    if EXTENSION:
        summary = (
            f"{len(endpoints)} whitelisted endpoints · "
            f"[{len(doctypes)} custom DocTypes](doctypes.md) · "
            "[OpenAPI spec](../openapi.json)"
        )
    else:
        summary = (
            f"{len(endpoints)} whitelisted endpoints across {len(APPS)} apps · "
            f"[{len(doctypes)} custom DocTypes](doctypes.md) · "
            "[OpenAPI spec](../openapi.json) · [browse in Redoc](../index.html)"
        )
    lines = [
        "# API reference index",
        "",
        EXTENSION_BANNER if EXTENSION else GENERATED_BANNER,
        "",
        summary,
        "",
    ]
    for app in documented_apps():
        app_eps = [e for e in endpoints if e["app"] == app]
        lines += [f"## {app} ({len(app_eps)})", ""]
        lines += ["| module | endpoints |", "|---|---|"]
        for module, eps in sorted(group_by_module(app_eps).items()):
            rel = module_doc_relpath(app, module)
            names = ", ".join(f"`{e['name']}`" for e in eps)
            lines.append(f"| [`{module}`]({rel}) | {names} |")
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


def render_doctypes_md(doctypes: list[dict]) -> str:
    rest = "the POS core's docs/api/frappe-rest.md" if EXTENSION else "../frappe-rest.md"
    lines = [
        "# Custom DocType reference",
        "",
        EXTENSION_BANNER if EXTENSION else GENERATED_BANNER,
        "",
        "CRUD via Frappe REST: `GET|POST /api/resource/<DocType>`, "
        f"`GET|PUT|DELETE /api/resource/<DocType>/<name>` (see {rest}). "
        "Child tables (`istable`) are only reachable embedded in their parent. "
        "The same shapes are modelled as `components.schemas` in the OpenAPI "
        "spec.",
        "",
    ]
    for dt in doctypes:
        flags = [
            f
            for f, on in (
                ("single", dt["issingle"]),
                ("submittable", dt["is_submittable"]),
                ("child table", dt["istable"]),
            )
            if on
        ]
        lines += [f"## {dt['name']}", ""]
        meta = f"app: `{dt['app']}` · module: {dt['module']}"
        if flags:
            meta += " · " + ", ".join(flags)
        if dt["roles"] and any(dt["roles"]):
            meta += " · roles: " + ", ".join(r for r in dt["roles"] if r)
        lines += [meta, ""]
        if dt["description"]:
            lines += [dt["description"], ""]
        lines += ["| field | type | label | reqd | options |", "|---|---|---|---|---|"]
        for f in dt["fields"]:
            lines.append(
                "| `{}` | {} | {} | {} | {} |".format(
                    f["fieldname"],
                    f["fieldtype"],
                    md_escape(f["label"]),
                    "✓" if f["reqd"] else "",
                    md_escape(f["options"]),
                )
            )
        lines.append("")
    return "\n".join(lines).rstrip() + "\n"


# --------------------------------------------------------------------- main


def write(path: Path, content: str):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")


def render(endpoints: list[dict], doctypes: list[dict]) -> dict[str, str]:
    """Every generated file: path relative to the output directory → content."""
    spec = build_openapi(endpoints, doctypes)
    if len(spec["paths"]) != len(endpoints):
        raise SystemExit(
            "path collision — dotted paths must be unique "
            f"({len(spec['paths'])} paths vs {len(endpoints)} endpoints)"
        )
    files = {"openapi.json": json.dumps(spec, indent=2, ensure_ascii=False) + "\n"}
    for module, eps in sorted(group_by_module(endpoints).items()):
        files["reference/" + module_doc_relpath(eps[0]["app"], module)] = render_module_md(module, eps)
    files["reference/README.md"] = render_index_md(endpoints, doctypes)
    files["reference/doctypes.md"] = render_doctypes_md(doctypes)
    return files


CATALOG_NAME = "api_catalog.json"


def first_sentence(text: str, limit: int) -> str:
    """The first sentence of ``text``, cut to ``limit`` characters."""
    text = " ".join(text.split())
    text = re.split(r"(?<=[.!?])\s", text, maxsplit=1)[0]
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def clip(text: str, limit: int) -> str:
    text = " ".join(text.split())
    return text if len(text) <= limit else text[: limit - 1].rstrip() + "…"


def catalog_row(ep: dict) -> dict:
    """One endpoint as the action catalog lists it (ffl_core.api.action_catalog)."""
    args = []
    for p in ep["params"]:
        kind = p["schema"].get("type")
        if isinstance(kind, list):
            kind = "|".join(kind)
        args.append({"name": p["name"], "type": kind or "any", "required": p["required"],
            "desc": first_sentence(p.get("desc", ""), 200)})
    return {
        "method": ep["dotted"],
        "module": ep["module"],
        "summary": clip(ep["doc"]["summary"], 200),
        "description": clip(ep["doc"]["description"], 600),
        "args": args,
        "returns": clip(section_text(ep, "Returns"), 300),
        "http": ep["methods"],
        "guest": ep["allow_guest"],
        "auth": ep["auth"],
        "source": f"{ep['file']}:{ep['line']}",
    }


def catalog_path(app: str) -> Path:
    """Inside the app package, so the image (COPY apps/<app>) and an installed extension ship it."""
    return app_root(app) / app / CATALOG_NAME


def render_catalogs(endpoints: list[dict]) -> dict[Path, str]:
    """apps/<app>/<app>/api_catalog.json per documented app (--app: <root>/<id>/api_catalog.json):
    one compact row per endpoint, sorted by dotted path, no timestamps."""
    out = {}
    for app in documented_apps():
        if not (app_root(app) / app).is_dir():
            continue
        rows = [json.dumps(catalog_row(ep), ensure_ascii=False, separators=(",", ":"))
            for ep in endpoints if ep["app"] == app]
        out[catalog_path(app)] = "[\n" + ",\n".join(rows) + "\n]\n" if rows else "[]\n"
    return out


def stale_catalogs(catalogs: dict[Path, str]) -> list[str]:
    """How the api_catalog.json files on disk differ from ``catalogs`` (empty = fresh)."""
    problems = []
    for path, content in catalogs.items():
        rel = cited(path)
        if not path.is_file():
            problems.append(f"{rel} — missing")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"{rel} — out of date")
    return sorted(problems)


def stale_files(out: Path, files: dict[str, str]) -> list[str]:
    """How the generated files under ``out`` differ from ``files`` (empty = fresh)."""
    problems = []
    for rel, content in files.items():
        path = out / rel
        if not path.is_file():
            problems.append(f"{rel} — missing")
        elif path.read_text(encoding="utf-8") != content:
            problems.append(f"{rel} — out of date")
    reference = out / "reference"
    for path in reference.rglob("*.md") if reference.is_dir() else []:
        rel = path.relative_to(out).as_posix()
        if rel not in files:
            problems.append(f"{rel} — no longer generated")
    return sorted(problems)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="run the verification suite (token parity + docstring "
        "conformance) and exit 1 on any failure; with --app, exit 3 when "
        "the only failure is files under --out that are not a fresh generation",
    )
    parser.add_argument(
        "--app",
        metavar="ROOT",
        help="document one extension instead of the core apps: its app root "
        "(the directory holding pyproject.toml and <id>/hooks.py)",
    )
    parser.add_argument(
        "--out",
        metavar="DIR",
        help="output directory (default: the core's docs/api, or ROOT/docs/api with --app)",
    )
    opts = parser.parse_args(argv)

    if opts.app:
        use_extension(opts.app)
    base = EXTENSION["root"] if EXTENSION else REPO
    out = Path(opts.out).resolve() if opts.out else (base / "docs" / "api" if EXTENSION else OUT)

    resolver = AuthResolver()
    endpoints = collect_endpoints(resolver)
    doctypes = collect_doctypes()

    catalogs = render_catalogs(endpoints)
    if opts.check:
        stale = stale_files(out, render(endpoints, doctypes)) if EXTENSION else []
        stale_catalog = stale_catalogs(catalogs)
        status = run_checks(endpoints, doctypes, stale=bool(stale or stale_catalog))
        if stale_catalog:
            print("STALE — the action catalog (api_catalog.json) is not a fresh generation:", file=sys.stderr)
            for line in stale_catalog:
                print(f"  {line}", file=sys.stderr)
            if not EXTENSION:
                # The core gates its catalogs here: they ship in the image, and docs/api's git diff does not see them.
                print("  run 'make api-docs' and commit the api_catalog.json files", file=sys.stderr)
                status = 1 if status in (0, 3) else status
        if stale:
            print(f"STALE — {out} is not a fresh generation:", file=sys.stderr)
            for line in stale:
                print(f"  {line}", file=sys.stderr)
        if EXTENSION and (stale or stale_catalog):
            # No path: make ext-test and CI check a copy (apps-ext/<id>, ext/<id>) that the next run replaces.
            print("  regenerate on your machine, from an OpenGunstore checkout, against the extension's own "
                "folder (not a copy of it), and commit docs/api and <id>/api_catalog.json:", file=sys.stderr)
            print("    python3 scripts/generate_api_docs.py --app <extension folder>"
                + (" --out <dir>" if opts.out else ""), file=sys.stderr)
        return status

    files = render(endpoints, doctypes)
    # wipe generated markdown so deleted modules disappear
    ref = out / "reference"
    if ref.exists():
        for old in ref.rglob("*.md"):
            old.unlink()
    for rel, content in files.items():
        write(out / rel, content)
    for path, content in catalogs.items():
        write(path, content)

    try:
        shown = out.relative_to(base)
    except ValueError:
        shown = out
    print(
        f"generated: {len(endpoints)} endpoints, {len(group_by_module(endpoints))} modules, "
        f"{len(doctypes)} doctypes → {shown}/"
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
