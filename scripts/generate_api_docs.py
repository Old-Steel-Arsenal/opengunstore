#!/usr/bin/env python3
"""Generate the OpenGunstore API reference from source (docs/api/).

Static AST introspection over the three custom apps — no running bench
required, so CI can enforce freshness in seconds (`make api-docs-check`).

`--app <extension root>` documents one extension instead (
its endpoints carry the same docstring standard), into `<root>/docs/api` by
default: the same openapi.json + reference/ layout for that one app. Its gates
resolve through the core apps of this checkout, so `require_enabled(APP,
roles=COUNTER_ROLES)` publishes the real role names. With --app, `--check`
also compares the files under --out with a fresh generation (an extension's
CI has no `git diff` gate of its own) and exits 3 when they are the only
failure; parity and conformance failures exit 1, stale files or not. A
Permissions section whose role list contradicts a gate resolved through the
core (COUNTER_ROLES and the like) is drift there, not a failure: the core
changing its roles makes it with nothing changed in the extension — 3 too.
A contradiction that stands with the core's role names left out is the
extension's own: 1.

Outputs (all deterministic — stable ordering, no timestamps):
  docs/api/openapi.json           OpenAPI 3.1 spec (endpoints + DocType schemas)
  docs/api/reference/README.md    index: endpoint counts per module
  docs/api/reference/<app>/<module>.md   per-module endpoint reference
  docs/api/reference/doctypes.md  custom DocType field reference (from schema JSONs)
  apps/<app>/<app>/api_catalog.json   the action catalog ffl_core.api.action_catalog
      serves (one compact row per endpoint); with --app, <root>/<id>/api_catalog.json.
      --check fails (core: 1; --app: 3, stale) when one is not a fresh generation.

Standalone use: the script needs only Python 3 and a checkout, no bench. The
production hosts in openapi.json "servers" come from the environment, read when
the spec is built:
  API_DOCS_POS_API_URL   the external API entry
  API_DOCS_PROD_URL      the desk host
Both default to https://pos.example.com, which is what the committed docs/api is
generated with; when only one is set the other follows it (one server entry, no
placeholder duplicate). A deployment that publishes the docs regenerates them
with its own hosts, e.g.
  API_DOCS_POS_API_URL=https://api.shop.test python3 scripts/generate_api_docs.py

Auth derivation: for every endpoint the generator statically resolves the
role gate actually executed at the top of the function body
(frappe.only_for / gate helpers like _gate()/_check_perm() /
frappe.has_permission / get_roles() membership checks), following module
constants and one level of helper/function indirection across the three
apps. The resolved roles are emitted into the spec and Markdown, so a
change to a role constant produces a docs diff and trips the freshness
gate. The docstring's own Permissions section is kept as supplementary
semantics (what the machine can't infer).

Docstring convention (Google style, enforced by --check):
  Summary line.

  Free-form description.

  Args:
      name (type): description (continuation lines indented)
  Returns:
      description
  Raises / Permissions / Payload / Example / Notes:
      ...

`--check` runs the verification suite and exits non-zero on failure:
  * parity: a tokenize-level scan (string literals excluded) of every
    whitelist decorator vs the AST extraction — any indented / nested /
    bare `@whitelist` decorator invisible to the AST pass FAILS the run
    instead of silently missing an endpoint;
  * conformance: every endpoint must have a docstring with a Returns
    section and (when it takes parameters) an Args or Payload section.
"""

