def is_whitelist(deco: ast.expr) -> bool:
    target = deco.func if isinstance(deco, ast.Call) else deco
    return (
        isinstance(target, ast.Attribute)
        and target.attr == "whitelist"
        and isinstance(target.value, ast.Name)
        and target.value.id == "frappe"
    )


def deco_kwargs(deco: ast.expr) -> dict:
    if not isinstance(deco, ast.Call):
        return {}
    out = {}
    for kw in deco.keywords:
        if kw.arg is None:
            continue
        try:
            out[kw.arg] = ast.literal_eval(kw.value)
        except (ValueError, SyntaxError):
            out[kw.arg] = None
    return out


def annotation_schema(node: ast.expr | None) -> dict:
    """Best-effort JSON-schema fragment from a type annotation."""
    if node is None:
        return {}
    text = ast.unparse(node)
    nullable = False
    m = re.fullmatch(r"(?:typing\.)?Optional\[(.+)\]", text)
    if m:
        text, nullable = m.group(1), True
    elif "| None" in text or "None |" in text:
        text = text.replace("| None", "").replace("None |", "").strip()
        nullable = True
    base = schema_for_type_name(text)
    if not base:
        base = {"description": f"({text})"}
    if nullable and "type" in base:
        base["type"] = [base["type"], "null"]
    return base


def schema_for_type_name(text: str) -> dict:
    return dict(TYPE_MAP.get(text.split("[")[0], {}))


def parse_docstring(doc: str | None) -> dict:
    """Split a docstring into summary / description / named sections."""
    result = {"summary": "", "description": "", "sections": {}}
    if not doc:
        return result
    lines = doc.strip().splitlines()
    section = None
    buf: list[str] = []
    body: list[str] = []

    def flush():
        nonlocal buf
        if section:
            # A repeated section header appends rather than silently
            # overwriting the earlier block.
            result["sections"].setdefault(section, []).extend(buf)
        buf = []

    for line in lines:
        header = line.strip().rstrip(":")
        if line.strip().endswith(":") and header in DOCSTRING_SECTIONS:
            flush()
            section = "Example" if header == "Examples" else header
            continue
        (buf if section else body).append(line)
    flush()

    if body:
        result["summary"] = body[0].strip()
        result["description"] = "\n".join(body[1:]).strip()
    return result


def parse_args_section(lines: list[str]) -> dict[str, dict]:
    """Parse an Args: block into {name: {"type":…, "desc":…}}.

    Entry lines share the indent of the first entry; anything indented
    deeper is a continuation of the previous entry's description.
    """
    out: dict[str, dict] = {}
    current = None
    entry_indent = None
    for raw in lines:
        line = raw.strip()
        if not line:
            continue
        indent = len(raw) - len(raw.lstrip())
        m = re.match(r"^(\*{0,2}\w+)\s*(?:\(([^)]+)\))?\s*:\s*(.*)$", line)
        if m and (entry_indent is None or indent <= entry_indent):
            entry_indent = indent if entry_indent is None else entry_indent
            current = m.group(1).lstrip("*")
            out[current] = {"type": m.group(2) or "", "desc": m.group(3)}
        elif current:
            out[current]["desc"] = (out[current]["desc"] + " " + line).strip()
    return out


