def use_extension(root: Path | str) -> dict:
    """Document the extension checked out at ``root`` instead of the core apps."""
    global EXTENSION
    root = Path(root).resolve()
    packages = sorted(p for p in root.iterdir() if (p / "hooks.py").is_file()) if root.is_dir() else []
    if len(packages) != 1:
        raise SystemExit(
            f"--app {root}: expected the extension's app root — the directory holding "
            "pyproject.toml and exactly one <id>/hooks.py package"
        )
    hooks = {
        node.targets[0].id: node.value.value
        for node in parse_source(packages[0] / "hooks.py").body
        if isinstance(node, ast.Assign) and len(node.targets) == 1
        and isinstance(node.targets[0], ast.Name) and isinstance(node.value, ast.Constant)
    }
    app_id = packages[0].name
    EXTENSION = {
        "id": app_id,
        "root": root,
        "title": hooks.get("app_title") or app_id,
        "description": hooks.get("app_description") or "",
    }
    return EXTENSION


def iter_app_sources():
    """Every non-test source file of the documented apps — the single definition
    of "our source", shared by the AST pass and the token parity scan."""
    for app in documented_apps():
        pkg = app_root(app) / app
        for path in sorted(pkg.rglob("*.py")):
            # parts inside the package: a checkout may sit under any folder (deploy/prod/tests/ext_hello)
            if "tests" in path.relative_to(pkg).parts or path.name.startswith("test_"):
                continue
            yield app, pkg, path


def read_source(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def parse_source(path: Path) -> ast.Module:
    try:
        return ast.parse(read_source(path))
    except SyntaxError as exc:
        raise SystemExit(f"syntax error while parsing {path}: {exc}") from exc


