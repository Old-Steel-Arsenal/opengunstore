def collect_endpoints(resolver: AuthResolver) -> list[dict]:
    endpoints = []
    # --app: each role gate derived again with the core's role names left out (conformance_problems' drift)
    own_resolver = AuthResolver(core_roles=False) if EXTENSION else None
    for app, pkg, path in iter_app_sources():
        tree = parse_source(path)
        module = ".".join([app] + list(path.relative_to(pkg).with_suffix("").parts))
        if module.endswith(".__init__"):
            module = module[: -len(".__init__")]
        for node in tree.body:  # module level only (frappe requirement)
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            wl = [d for d in node.decorator_list if is_whitelist(d)]
            if not wl:
                continue
            kwargs = deco_kwargs(wl[0])
            args = node.args
            if args.posonlyargs or args.kwonlyargs or args.vararg:
                print(
                    f"WARNING: {module}.{node.name} uses positional-only/"
                    "keyword-only/*args parameters — not modelled by the "
                    "generator; document them explicitly in the docstring.",
                    file=sys.stderr,
                )
            params = []
            defaults = [None] * (len(args.args) - len(args.defaults)) + list(args.defaults)
            for arg, default in zip(args.args, defaults):
                if arg.arg in ("self", "cls"):
                    continue
                params.append(
                    {
                        "name": arg.arg,
                        "schema": annotation_schema(arg.annotation),
                        "required": default is None,
                        "default": ast.unparse(default) if default else None,
                    }
                )
            if args.kwarg:
                params.append(
                    {
                        "name": f"**{args.kwarg.arg}",
                        "schema": {},
                        "required": False,
                        "default": None,
                    }
                )
            raw_doc = ast.get_docstring(node)
            doc = parse_docstring(raw_doc)
            arg_docs = parse_args_section(doc["sections"].get("Args", []))
            for p in params:
                info = arg_docs.get(p["name"].lstrip("*"), {})
                p["desc"] = info.get("desc", "")
                if info.get("type") and not p["schema"]:
                    p["schema"] = schema_for_type_name(info["type"])
            allow_guest = bool(kwargs.get("allow_guest"))
            # allow_guest endpoints are signature-verified webhooks —
            # their contract is the HMAC, not a role gate.
            auth = None if allow_guest else resolver.derive(node, module)
            own = own_resolver.derive(node, module) if own_resolver and auth and "roles" in auth else None
            endpoints.append(
                {
                    "app": app,
                    "module": module,
                    "name": node.name,
                    "dotted": f"{module}.{node.name}",
                    "file": cited(path),
                    "line": node.lineno,
                    "allow_guest": allow_guest,
                    "methods": kwargs.get("methods") or ["POST"],
                    "params": params,
                    "return_schema": annotation_schema(node.returns),
                    "has_doc": bool(raw_doc),
                    "doc": doc,
                    "auth": auth,
                    "own_roles": (own or {}).get("roles", []),
                }
            )
    return sorted(endpoints, key=lambda e: e["dotted"])


def collect_doctypes() -> list[dict]:
    doctypes = []
    for app in documented_apps():
        for path in sorted(app_root(app).rglob("doctype/*/*.json")):
            if path.parent.name != path.stem:
                continue
            data = json.loads(read_source(path))
            if data.get("doctype") != "DocType":
                continue
            doctypes.append(
                {
                    "app": app,
                    "name": data["name"],
                    "module": data.get("module", ""),
                    "issingle": bool(data.get("issingle")),
                    "is_submittable": bool(data.get("is_submittable")),
                    "istable": bool(data.get("istable")),
                    "description": (data.get("description") or "").strip(),
                    "fields": [
                        {
                            "fieldname": f.get("fieldname", ""),
                            "fieldtype": f.get("fieldtype", ""),
                            "label": f.get("label", ""),
                            "reqd": bool(f.get("reqd")),
                            "options": (f.get("options") or "").replace("\n", ", "),
                            "raw_options": f.get("options") or "",
                        }
                        for f in data.get("fields", [])
                        if f.get("fieldtype")
                        not in ("Section Break", "Column Break", "Tab Break", "HTML")
                    ],
                    "roles": sorted(
                        {p.get("role", "") for p in data.get("permissions", [])}
                    ),
                    "file": cited(path),
                }
            )
    return sorted(doctypes, key=lambda d: (d["app"], d["name"]))


