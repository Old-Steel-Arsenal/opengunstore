def absolute_import_module(current_module: str, node: ast.ImportFrom) -> str | None:
    """Absolute dotted module for an ImportFrom, resolving relative levels."""
    if not node.level:
        return node.module
    base = current_module.split(".")[: -node.level]
    if not base:
        return None
    return ".".join(base + ([node.module] if node.module else []))


def imports_from(nodes, current_module: str) -> dict[str, tuple[str, str]]:
    out: dict[str, tuple[str, str]] = {}
    for node in nodes:
        if isinstance(node, ast.ImportFrom):
            src = absolute_import_module(current_module, node)
            if src:
                for alias in node.names:
                    out[alias.asname or alias.name] = (src, alias.name)
    return out


class ModuleIndex:
    """Module-level AST facts the permission resolver needs."""

    def __init__(self, tree: ast.Module, module: str):
        self.constants: dict[str, ast.expr] = {}
        self.imports = imports_from(tree.body, module)
        # Fallback map including function-local imports anywhere in the file
        # (the lazy-import-to-break-cycles pattern); only consulted when the
        # module-level map misses, so a top-level import always wins.
        self.deep_imports = imports_from(
            [n for n in ast.walk(tree) if isinstance(n, ast.ImportFrom)], module)
        self.functions: dict[str, ast.FunctionDef] = {}
        for node in tree.body:
            if (
                isinstance(node, ast.Assign)
                and len(node.targets) == 1
                and isinstance(node.targets[0], ast.Name)
            ):
                self.constants[node.targets[0].id] = node.value
            elif isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                self.functions[node.name] = node


class AuthResolver:
    """Statically resolve the role gate executed at the top of an endpoint.

    Depth-limited, cross-module (our three apps only), and honest about
    failure: anything unresolvable degrades to a named runtime label, never
    to invented roles.
    """

    def __init__(self, core_roles: bool = True):
        self._index_cache: dict[str, ModuleIndex | None] = {}
        # False (--app): a role name written in a core module resolves to nothing — the gate as the extension alone
        # spells it, which conformance_problems tells drift from a defect by
        self.core_roles = core_roles

    # -- module plumbing ---------------------------------------------------

    def _module_path(self, dotted: str) -> Path | None:
        parts = dotted.split(".")
        if parts[0] not in APPS and parts[0] not in documented_apps():
            return None
        base = app_root(parts[0]) / parts[0]
        for candidate in (
            base.joinpath(*parts[1:]).with_suffix(".py") if len(parts) > 1 else base / "__init__.py",
            base.joinpath(*parts[1:], "__init__.py"),
        ):
            if candidate.exists():
                return candidate
        return None

    def index(self, dotted: str) -> ModuleIndex | None:
        if dotted not in self._index_cache:
            path = self._module_path(dotted)
            self._index_cache[dotted] = (
                ModuleIndex(parse_source(path), dotted) if path else None
            )
        return self._index_cache[dotted]

    # -- expression → roles ------------------------------------------------

    def roles_from_expr(self, expr: ast.expr, module: str, depth: int = 6):
        """Return a list of role names, or None when unresolvable.

        Structural recursion (tuples / concatenation) keeps the depth
        budget; only indirection hops (names / imports / calls) spend it.
        """
        if depth <= 0:
            return None
        if isinstance(expr, ast.Constant) and isinstance(expr.value, str):
            return [expr.value] if self.core_roles or module.split(".")[0] not in APPS else []
        if isinstance(expr, (ast.Tuple, ast.List, ast.Set)):
            roles: list[str] = []
            for element in expr.elts:
                sub = self.roles_from_expr(element, module, depth)
                if sub is None:
                    return None
                roles.extend(sub)
            return roles
        if isinstance(expr, ast.BinOp) and isinstance(expr.op, ast.Add):
            left = self.roles_from_expr(expr.left, module, depth)
            right = self.roles_from_expr(expr.right, module, depth)
            if left is None or right is None:
                return None
            return left + [role for role in right if role not in left]
        if isinstance(expr, ast.Name):
            return self.roles_from_name(module, expr.id, depth - 1)
        if isinstance(expr, ast.Attribute) and isinstance(expr.value, ast.Name):
            # api.ORDER_ROLES — attribute on an imported submodule
            idx = self.index(module)
            if idx:
                hit = idx.imports.get(expr.value.id) or idx.deep_imports.get(expr.value.id)
                if hit:
                    return self.roles_from_name(f"{hit[0]}.{hit[1]}", expr.attr, depth - 1)
        if isinstance(expr, ast.Call) and isinstance(expr.func, ast.Name):
            if expr.func.id in ("tuple", "list", "set", "sorted", "frozenset") and expr.args:
                return self.roles_from_expr(expr.args[0], module, depth)
            return self.roles_from_function_call(module, expr.func.id, depth - 1)
        return None

    def roles_from_name(self, module: str, name: str, depth: int):
        idx = self.index(module)
        if idx is None or depth <= 0:
            return None
        if name in idx.constants:
            return self.roles_from_expr(idx.constants[name], module, depth)
        hit = idx.imports.get(name) or idx.deep_imports.get(name)
        if hit:
            return self.roles_from_name(hit[0], hit[1], depth - 1)
        if name in idx.functions:
            return self._roles_from_function_def(idx.functions[name], module, depth - 1)
        return None

    def roles_from_function_call(self, module: str, name: str, depth: int):
        idx = self.index(module)
        if idx is None or depth <= 0:
            return None
        if name in idx.functions:
            return self._roles_from_function_def(idx.functions[name], module, depth - 1)
        if name in idx.imports:
            src_module, src_name = idx.imports[name]
            return self.roles_from_function_call(src_module, src_name, depth - 1)
        return None

    def _roles_from_function_def(self, node: ast.FunctionDef, module: str, depth: int):
        returns = [n.value for n in ast.walk(node) if isinstance(n, ast.Return) and n.value]
        roles: list[str] = []
        for value in returns:
            sub = self.roles_from_expr(value, module, depth)
            if sub is None:
                return None
            for role in sub:
                if role not in roles:
                    roles.append(role)
        return roles or None

    # -- statement scanning ------------------------------------------------

    @staticmethod
    def _is_attr_call(call: ast.expr, obj: str, attr: str) -> bool:
        return (
            isinstance(call, ast.Call)
            and isinstance(call.func, ast.Attribute)
            and call.func.attr == attr
            and isinstance(call.func.value, ast.Name)
            and call.func.value.id == obj
        )

    def _roles_from_set_op(self, node, module: str):
        """Role constants inside `set(X) & get_roles()` / `.intersection()`
        gate shapes — the one rule, shared by every site that meets it."""
        if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitAnd):
            candidates = [node.left, node.right]
        elif (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr == "intersection"
        ):
            candidates = [node.func.value, *node.args]
        else:
            return None
        for candidate in candidates:
            roles = self.roles_from_expr(candidate, module)
            if roles:
                return {"roles": roles}
        return None

    def _imports_seen(self, module: str, local_imports: dict | None) -> dict:
        imports = dict(local_imports or {})
        idx = self.index(module)
        if idx:
            imports.update(idx.imports)
        return imports

    def _auth_from_call(self, call: ast.Call, module: str, depth: int,
            local_imports: dict | None = None, in_test: bool = False):
        if (
            isinstance(call.func, ast.Name)
            and self._imports_seen(module, local_imports).get(call.func.id)
            == ("ffl_core.extensions", "require_enabled")
        ):
            # The extension SDK gate: refuses while the
            # store has the extension switched off, and — with roles= — a
            # caller holding none of them. Only the name imported from the
            # SDK counts; a local look-alike proves nothing.
            roles_expr = next((kw.value for kw in call.keywords if kw.arg == "roles"), None)
            if roles_expr is None:
                return {"switch": True}
            roles = self.roles_from_expr(roles_expr, module)
            if roles is not None:
                return {"roles": roles, "switch": True}
            return {"label": ast.unparse(roles_expr), "switch": True}
        if self._is_attr_call(call, "frappe", "only_for") and call.args:
            roles = self.roles_from_expr(call.args[0], module)
            if roles is not None:
                return {"roles": roles}
            return {"label": ast.unparse(call.args[0])}
        if self._is_attr_call(call, "frappe", "has_permission"):
            doctype = None
            ptype = "read"
            throws = False
            if call.args and isinstance(call.args[0], ast.Constant):
                doctype = call.args[0].value
            if len(call.args) > 1 and isinstance(call.args[1], ast.Constant):
                ptype = call.args[1].value
            for kw in call.keywords:
                if kw.arg == "ptype" and isinstance(kw.value, ast.Constant):
                    ptype = kw.value.value
                if kw.arg == "throw" and isinstance(kw.value, ast.Constant):
                    throws = bool(kw.value.value)
            # Only a PROVABLY throwing form is a gate: a bare
            # has_permission(...) whose return value is discarded is a
            # no-op, and publishing it as a gate would be a false
            # guarantee. Inside an `if not …:` test
            # the enforcement lives in the If BODY, which the caller
            # judges (hard when it throws, soft when it returns).
            if doctype and (throws or in_test):
                return {"perm": f"{ptype} permission on {doctype}",
                        "perm_doctype": doctype, "perm_ptype": ptype}
            return None
        if isinstance(call.func, ast.Name) and self._gate_shaped(call.func.id):
            # A local (or imported) gate helper — resolve its body. Only
            # gate-shaped names qualify: deep-walking arbitrary business
            # calls would claim gates a branch can skip (the exact false
            # guarantee.
            idx = self.index(module)
            target, target_module = None, module
            imports = self._imports_seen(module, local_imports)
            if idx and call.func.id in idx.functions:
                target = idx.functions[call.func.id]
            elif call.func.id in imports:
                src_module, src_name = imports[call.func.id]
                src_idx = self.index(src_module)
                if src_idx and src_name in src_idx.functions:
                    target, target_module = src_idx.functions[src_name], src_module
            if target is not None and depth > 0:
                # helper body is in ITS module — the caller's local imports
                # must not leak across the module boundary. TOP-LEVEL
                # statements only, exactly like an endpoint body: a
                # permission call buried in a helper's nested branches is
                # conditional business logic, and claiming it as the gate
                # is the false-guarantee shape, shown
                # with a sandbox counterexample.
                return self._auth_from_helper_body(target, target_module, depth - 1)
        if (
            isinstance(call.func, ast.Attribute)
            and isinstance(call.func.value, ast.Name)
            and self._gate_shaped(call.func.attr)
            and depth > 0
        ):
            # `api._check_refund_perm()` — a gate helper reached through an imported
            # module of our apps (`from ffl_integrations.payments import api`).
            hit = self._imports_seen(module, local_imports).get(call.func.value.id)
            target_module = f"{hit[0]}.{hit[1]}" if hit else None
            target_idx = self.index(target_module) if target_module else None
            if target_idx and call.func.attr in target_idx.functions:
                return self._auth_from_helper_body(
                    target_idx.functions[call.func.attr], target_module, depth - 1)
        return None

    def _auth_from_helper_body(self, target: ast.FunctionDef, module: str, depth: int):
        auth, gates = None, set()
        for i, stmt in enumerate(target.body):
            found = self._auth_from_stmt(stmt, module, depth, None)
            # gate helpers of the `return bool(set(ROLES) & get_roles())`
            # shape — the boolean is the helper's WHOLE result, so reading
            # roles off the return expression is sound (the caller's
            # `if not helper():` decides hard vs soft).
            if not found and isinstance(stmt, ast.Return) and stmt.value is not None:
                for node in ast.walk(stmt.value):
                    found = self._roles_from_set_op(node, module)
                    if found:
                        break
            if found:
                # A gate reached after code that did something is late, as in an
                # endpoint body — the first gate and, scanning on (an extension,
                # for the half still missing), a later one alike; reading the
                # caller's roles for the check is part of it (_substantive).
                if self._code_runs_before(target.body, i, gates):
                    found["late"] = True
                gates.add(i)
                auth = self._merge_gates(auth, found)
                if self._gates_complete(auth):
                    return auth
        return auth

    @staticmethod
    def _merge_gates(auth: dict | None, found: dict) -> dict:
        """An extension may check the store's switch and the caller's roles or
        permission in two statements — `require_enabled(APP)` next to
        `only_for` / `has_permission`, in either order. The first role or
        permission gate and the switch together are the auth; a later gate
        that adds neither changes nothing (not even `late`)."""
        if auth is None:
            return found
        merged = dict(auth)
        adds_gate = not GATE_KEYS & auth.keys() and GATE_KEYS & found.keys()
        adds_switch = found.get("switch") and not auth.get("switch")
        if adds_gate:
            merged.update({k: v for k, v in found.items()
                if k in GATE_KEYS or k in PERM_DETAIL_KEYS or k == "soft"})
        if adds_switch:
            merged["switch"] = True
        if (adds_gate or adds_switch) and found.get("late"):
            merged["late"] = True
        return merged

    @staticmethod
    def _gates_complete(auth: dict) -> bool:
        """Stop scanning: the core documents its first gate; an extension (--app)
        also looks for the half — switch or role/permission gate — still missing."""
        return not EXTENSION or bool(auth.get("switch") and GATE_KEYS & auth.keys())

    @staticmethod
    def _gate_shaped(name: str) -> bool:
        lowered = name.lower()
        return name.startswith("_") and any(
            token in lowered for token in ("gate", "check", "perm", "role", "session")
        )

    def _auth_from_test(self, test: ast.expr, module: str,
            local_imports: dict | None = None):
        """Recognise gate-shaped `if not …: throw` membership tests."""
        if isinstance(test, ast.UnaryOp) and isinstance(test.op, ast.Not):
            inner = test.operand
            # not frappe.has_permission(...) / not _has_ship_role()
            if isinstance(inner, ast.Call):
                found = self._auth_from_call(
                    inner, module, 2, local_imports, in_test=True)
                if found:
                    return found
            # not (set(frappe.get_roles()) & ROLES)
            found = self._roles_from_set_op(inner, module)
            if found:
                return found
        if isinstance(test, ast.Compare) and any(
            isinstance(op, ast.NotIn) for op in test.ops
        ):
            # "System Manager" not in frappe.get_roles()
            roles = self.roles_from_expr(test.left, module)
            if roles:
                return {"roles": roles}
        return None

    @staticmethod
    def _body_throws(body) -> bool:
        for node in body:
            for sub in ast.walk(node):
                if isinstance(sub, ast.Raise):
                    return True
                if (
                    isinstance(sub, ast.Call)
                    and isinstance(sub.func, ast.Attribute)
                    and sub.func.attr == "throw"
                ):
                    return True
        return False

    def _auth_from_stmt(self, node, module: str, depth: int,
            local_imports: dict | None):
        if isinstance(node, ast.Expr) and isinstance(node.value, ast.Call):
            return self._auth_from_call(node.value, module, depth, local_imports)
        if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call):
            # e.g. `dealer = _dealer_for_session()` — the gate IS the call
            return self._auth_from_call(node.value, module, depth, local_imports)
        if isinstance(node, ast.If):
            found = self._auth_from_test(node.test, module, local_imports)
            if found and not self._body_throws(node.body):
                # `if not <gate>(): return {}` — a SOFT gate: the caller
                # is filtered, not rejected. Say so instead of rendering
                # it as a hard requirement.
                found = dict(found, soft=True)
            return found
        return None


    @staticmethod
    def _substantive(stmt) -> bool:
        """Pre-gate statement that actually DOES something an unauthorized
        caller shouldn't reach: any frappe.* call (DB reads, parse_json of
        attacker input, locks) or an early exit path — frappe.get_roles()
        aside: reading the caller's roles for the check
        (`roles = set(frappe.get_roles())`) is part of that check."""
        for node in ast.walk(stmt):
            if isinstance(node, ast.Return):
                return True
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Attribute):
                root = node.func
                while isinstance(root, ast.Attribute):
                    root = root.value
                if isinstance(root, ast.Name) and root.id == "frappe" and not (
                        node.func.attr == "get_roles" and node.func.value is root):
                    # frappe.parse_json / frappe.db.get_value / … all count
                    return True
        return False

    def _code_runs_before(self, body: list, i: int, gates: set) -> bool:
        """Substantive code among ``body[:i]`` — the statements already read as gates and imports aside."""
        return any(
            self._substantive(prev)
            for j, prev in enumerate(body[:i])
            if j not in gates and not isinstance(prev, (ast.Import, ast.ImportFrom))
        )

    def derive(self, node: ast.FunctionDef, module: str):
        """Auth facts for one endpoint.

        Scans every TOP-LEVEL statement of the body (never nested blocks —
        a nested permission call is business logic, not the entry gate) and
        records whether substantive code runs BEFORE the gate, so a
        late-positioned gate is reported honestly instead of implying a
        clean entry check. The core stops at the first gate; an extension
        keeps scanning until it has both the switch and a role/permission
        gate (_merge_gates).
        """
        # Function-local `from x import _ROLES` (the lazy-import pattern used
        # to break module cycles) — passed down so `only_for(_ROLES)` still
        # resolves to the source module's constant.
        local_imports = imports_from(node.body, module)
        auth, gates = None, set()
        for i, stmt in enumerate(node.body):
            found = self._auth_from_stmt(stmt, module, 3, local_imports)
            if not found:
                continue
            if self._code_runs_before(node.body, i, gates):
                found["late"] = True
            gates.add(i)
            auth = self._merge_gates(auth, found)
            if self._gates_complete(auth):
                return auth
        return auth


def auth_display(ep: dict) -> str:
    """One-line auth summary emitted into markdown + OpenAPI description."""
    if ep["allow_guest"]:
        return "Guest — no session; the endpoint verifies the caller itself (HMAC signature, HTTP Basic credentials or a one-time token)."
    auth = ep.get("auth")
    if not auth:
        return (
            "Any authenticated user — no explicit role gate at function "
            "entry (deliberate open reads document this in Permissions)."
        )
    late = (
        " (the gate is not the first statement — some code executes before "
        "this check)"
        if auth.get("late")
        else ""
    )
    switch = " — and only while the extension is switched on" if auth.get("switch") else ""
    if auth.get("switch") and not GATE_KEYS & auth.keys():
        return (
            "Any authenticated user, only while the extension is switched on — "
            f"no role gate at function entry{late}."
        )
    if "roles" in auth and auth.get("soft"):
        return (
            "Role-filtered: callers without Roles "
            + " / ".join(auth["roles"])
            + " receive an EMPTY result instead of an error" + switch + late + "."
        )
    if "roles" in auth:
        return "Roles: " + " / ".join(auth["roles"]) + switch + late
    if "perm" in auth and auth.get("soft"):
        return (
            f"Permission-filtered: callers without {auth['perm']} receive a "
            f"degraded/empty result instead of an error{switch}{late}."
        )
    if "perm" in auth:
        return f"Requires {auth['perm']} (Frappe DocType permission check){switch}{late}."
    return f"Roles resolved at runtime via `{auth['label']}`{switch}{late}."


def section_text(ep: dict, name: str) -> str:
    """A docstring section flattened to one paragraph — the single join
    used everywhere (markdown + OpenAPI), so wrapped lines can never be
    mangled into fake separators."""
    lines = ep["doc"]["sections"].get(name, [])
    return " ".join(line.strip() for line in lines if line.strip())


