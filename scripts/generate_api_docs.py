def token_whitelist_scan() -> tuple[int, list[str]]:
    """Count whitelist decorators at token level (string literals excluded).

    Returns (module_level_count, offenders). Offenders are decorators the
    AST pass cannot see: indented `@frappe.whitelist` (class methods /
    nested defs) and bare `@whitelist` from-imports — parity must FAIL on
    them rather than silently under-document.
    """
    count = 0
    offenders: list[str] = []
    significant = {
        tokenize.NEWLINE, tokenize.INDENT, tokenize.DEDENT, tokenize.ENCODING,
    }
    for _app, _pkg, path in iter_app_sources():
        source = read_source(path)
        # `from frappe import whitelist [as X]` makes every use invisible to
        # the AST pass (which matches only frappe.whitelist) — any decorator
        # spelled with the imported name is an offender.
        aliases = set()
        for m in re.finditer(r"^from\s+frappe\s+import\s+([^\n#]+)", source, re.M):
            for part in m.group(1).split(","):
                bits = part.strip().split()
                if bits and bits[0] == "whitelist":
                    aliases.add(bits[-1])  # 'whitelist' or its 'as' alias
        toks = list(tokenize.generate_tokens(io.StringIO(source).readline))
        for i, tok in enumerate(toks):
            if tok.type != tokenize.OP or tok.string != "@":
                continue
            j = i - 1  # decorator '@' begins a logical line; matmul never does
            while j >= 0 and toks[j].type in (tokenize.COMMENT, tokenize.NL):
                j -= 1
            if j >= 0 and toks[j].type not in significant:
                continue
            names = []
            k = i + 1
            while k < len(toks) and len(names) < 3:
                if toks[k].type == tokenize.NAME:
                    names.append(toks[k].string)
                elif not (toks[k].type == tokenize.OP and toks[k].string == "."):
                    break
                k += 1
            where = f"{cited(path)}:{tok.start[0]}"
            if names[:2] == ["frappe", "whitelist"]:
                if tok.start[1] == 0:
                    count += 1
                else:
                    offenders.append(f"{where} — non-module-level @frappe.whitelist")
            elif names[:1] == ["whitelist"] or (names and names[0] in aliases):
                offenders.append(
                    f"{where} — bare/aliased @{names[0]} (invisible to AST pass)")
    return count, offenders


def conformance_problems(endpoints: list[dict]) -> tuple[list[str], list[str], list[str]]:
    """The docstring standard, enforced: every endpoint documented, and any
    hand-written role names must agree with the derived gate (the derived
    line is authoritative; drifting prose fails CI rather than lying).

    Returns (undocumented, contradictions, drift). drift is --app only: a
    contradiction a core change alone makes — the
    gate's roles include role names written in the core, or the prose agrees
    with the gate once the core's role names are left out (own_roles, the
    vocabulary of the extension's own gates): only roles no gate of the
    extension names made the difference. The core's own run, and a
    contradiction that stands without the core's role names, is a
    contradiction."""
    vocabulary = {
        role
        for ep in endpoints
        if ep.get("auth") and "roles" in ep["auth"]
        for role in ep["auth"]["roles"]
    }
    own_vocabulary = {role for ep in endpoints for role in ep.get("own_roles", ())}
    undocumented, contradictions, drift = [], [], []
    for ep in endpoints:
        missing = []
        if not ep["has_doc"]:
            missing.append("docstring")
        else:
            has_params = any(not p["name"].startswith("**") for p in ep["params"])
            # A bare section HEADER with no content is as undocumented as a
            # missing one — require non-empty text.
            if has_params and not (section_text(ep, "Args") or section_text(ep, "Payload")):
                missing.append("Args")
            if not section_text(ep, "Returns"):
                missing.append("Returns")
        if missing:
            undocumented.append(f"{ep['file']}:{ep['line']} {ep['dotted']} — missing {', '.join(missing)}")
        auth = ep.get("auth") or {}
        if "roles" in auth:
            prose = section_text(ep, "Permissions")
            mentioned = {role for role in vocabulary if role in prose}
            if mentioned and mentioned != set(auth["roles"]):
                line = (
                    f"{ep['file']}:{ep['line']} {ep['dotted']} — Permissions prose "
                    f"role list ({', '.join(sorted(mentioned))}) contradicts the "
                    f"derived gate ({', '.join(sorted(auth['roles']))}); drop the "
                    "hand-written list or fix the gate"
                )
                own, own_mentioned = set(ep.get("own_roles", ())), {role for role in own_vocabulary if role in prose}
                via_core = EXTENSION and (own != set(auth["roles"]) or not own_mentioned or own_mentioned == own)
                (drift if via_core else contradictions).append(line)
    return undocumented, contradictions, drift


def run_checks(endpoints: list[dict], doctypes: list[dict], stale: bool = False) -> int:
    """Parity + conformance: 1 when either fails. Otherwise 3 when ``stale`` (the caller found stale
    files, --app: a warning in the core CI, which a core change alone can cause) or there is Permissions
    drift (--app, the same cause), and 0, "checks OK", when neither."""
    token_count, offenders = token_whitelist_scan()
    failed = False
    if offenders:
        failed = True
        print("PARITY FAIL — whitelist decorators the AST pass cannot see:", file=sys.stderr)
        for line in offenders:
            print(f"  {line}", file=sys.stderr)
    if token_count != len(endpoints):
        failed = True
        print(
            f"PARITY FAIL: token scan sees {token_count} module-level "
            f"@frappe.whitelist, AST extracted {len(endpoints)} — fix "
            "scripts/generate_api_docs.py",
            file=sys.stderr,
        )
    undocumented, contradictions, drift = conformance_problems(endpoints)
    for heading, lines in (
        ("CONFORMANCE FAIL — undocumented endpoints:", undocumented),
        ("CONFORMANCE FAIL — Permissions prose contradicts the derived gate:", contradictions),
    ):
        if lines:
            failed = True
            print(heading, file=sys.stderr)
            for line in lines:
                print(f"  {line}", file=sys.stderr)
    if drift:
        print("PERMISSIONS DRIFT — Permissions prose names other roles than the gate derived through this core "
            "(the core's roles changed; a warning, not a failure):", file=sys.stderr)
        for line in drift:
            print(f"  {line}", file=sys.stderr)
        print("  drop the hand-written role list from those Permissions sections — the derived line in the docs is "
            "authoritative, and that passes with this core and the one before — then regenerate docs/api.", file=sys.stderr)
    # Excluded test modules can still expose module-level whitelist methods
    # on an importable site — out of documentation scope, but say so.
    for app in documented_apps():
        pkg = app_root(app) / app
        for path in sorted(pkg.rglob("*.py")):
            if "tests" not in path.relative_to(pkg).parts and not path.name.startswith("test_"):
                continue
            n = len(re.findall(r"^@frappe\.whitelist", read_source(path), re.M))
            if n:
                print(
                    f"WARNING: {cited(path)} has {n} module-level "
                    "whitelist decorator(s) in an excluded test module — not "
                    "documented, but callable if the module imports on a site.",
                    file=sys.stderr,
                )
    if failed:
        return 1
    if stale or drift:
        return 3
    print(
        f"checks OK: {len(endpoints)} endpoints (token parity + docstring "
        f"conformance), {len(doctypes)} doctypes"
    )
    return 0


